def _chayuan_data_root() -> Path:
    return Path(os.environ.get("CHAYUAN_DATA") or os.environ.get("CHAYUAN_ROOT")
                or os.path.expanduser("~/.chayuan"))


def _llamacpp_models_dir() -> Path:
    p = _chayuan_data_root() / "vendor-data" / "llamacpp" / "models"
    p.mkdir(parents=True, exist_ok=True)
    return p


def _whispercpp_models_dir() -> Path:
    p = _chayuan_data_root() / "vendor-data" / "whispercpp" / "models"
    p.mkdir(parents=True, exist_ok=True)
    return p


def _comfyui_models_dir() -> Path:
    p = _chayuan_data_root() / "vendor-data" / "comfyui" / "models"
    p.mkdir(parents=True, exist_ok=True)
    return p


def _read_repo_id_from_manifest(model_path: Path) -> Optional[str]:
    """从 ``manifest.json`` 读 ``repo_id``;modelmgr.verifier 写的格式。"""
    mf = model_path / "manifest.json"
    if not mf.is_file():
        return None
    try:
        import json

        return json.loads(mf.read_text(encoding="utf-8")).get("repo_id")
    except Exception:  # noqa: BLE001
        return None


