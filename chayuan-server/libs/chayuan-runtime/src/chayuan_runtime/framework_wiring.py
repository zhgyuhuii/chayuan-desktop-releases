WireFn = Callable[[Path, str], WireOutcome]


_WIRE_TABLE: Dict[str, WireFn] = {
    "ollama": _wire_ollama,
    "vllm": _wire_vllm,
    "infinity": _wire_infinity,
    "llamacpp": _wire_llamacpp,
    "llama-cpp": _wire_llamacpp,
    "whispercpp": _wire_whispercpp,
    "whisper-cpp": _wire_whispercpp,
    "comfyui": _wire_comfyui,
    "funasr": _wire_funasr,
    "piper": _wire_funasr,
    "cosyvoice": _wire_funasr,
    "voxcpm2": _wire_funasr,        # VoxCPM 2 (TTS) 走通用 modality wrapper 路径
    "rapidocr": _wire_funasr,
    "paddleocr": _wire_funasr,
    "hf-cache": _wire_hf_cache,
}


def wire(model_path: str, capability: str, target_runtime: str) -> WireOutcome:
    """统一入口:按 ``target_runtime`` 分派到具体实现。

    返回 :class:`WireOutcome`;调用方(lifecycle)按 ``ok`` 决定下一步。
    """
    fn = _WIRE_TABLE.get(target_runtime.lower())
    if fn is None:
        return WireOutcome(
            ok=False, runtime=target_runtime,
            detail=f"未知运行时: {target_runtime};受支持: {sorted(_WIRE_TABLE)}",
        )
    p = Path(model_path)
    if not p.exists():
        return WireOutcome(
            ok=False, runtime=target_runtime,
            detail=f"模型路径不存在: {model_path}",
        )
    try:
        return fn(p, capability)
    except Exception as e:  # noqa: BLE001
        logger.exception("wire %s failed", target_runtime)
        return WireOutcome(
            ok=False, runtime=target_runtime,
            detail=f"wire {target_runtime} 抛异常: {type(e).__name__}: {e}",
        )


# ---------------------------------------------------------------------------
# 注入到 lifecycle
# ---------------------------------------------------------------------------

def install_into_lifecycle() -> None:
    """让 lifecycle WIRE 阶段调用本模块的 :func:`wire`。

    在进程启动早期(``server_app.startup``)调用一次即可。如果 lifecycle 还没
    import 也没事,本函数 import 失败时只 warn。
    """
    try:
        from chayuan_modelmgr.lifecycle import WireOutcome as _LcOutcome
        from chayuan_modelmgr.lifecycle import register_wire_impl

        def _adapter(model_path: str, capability: str, target_runtime: str) -> object:
            out = wire(model_path, capability, target_runtime)
            # 转成 lifecycle.WireOutcome 类型
            return _LcOutcome(
                ok=out.ok, runtime=out.runtime,
                detail=out.detail, extra=out.extra,
            )

        register_wire_impl(_adapter)
        logger.info("framework_wiring installed into lifecycle")
    except Exception as e:  # noqa: BLE001
        logger.warning("framework_wiring not installed: %s", e)


