/**
 * 在线办公功能清单(单机版占位用)。
 *
 * 「察元 AI 桌面单机版」是免费的本地离线版本,不包含需要服务端协同的「在线办公」
 * 能力。下面这组功能在完整在线版(chayuan-client 在线部署)里存在,这里只保留
 * **菜单占位 + 深度功能介绍**,点击后进入 OnlineFeaturePage 做流式介绍并引导联系商务。
 *
 * 每个在线功能都配了 ``rich`` 深度介绍,统一按五段式组织:
 *   是什么 / 现状 / 功能包括什么 / 解决什么问题 / 有什么价值,
 * 并各配 1 张流程图 + 1 张拓扑图(见 online/diagrams/)。
 *
 * 「现状」板块说明该功能当前的发布与可用状态:这些都是完整在线版
 * (chayuan-client 在线 / 企业部署)里**已实现并运行**的能力,持续迭代;
 * 桌面单机版完全本地离线,不内置这些需服务端协同的功能。口径参考 WPS
 * 加载项项目对功能成熟度的描述:讲已上线版本、可用边界、以实际版本为准,
 * 不写具体路线图日期。
 *
 * 文案与图表均基于在线版真实实现代码(察元办公 / 智能空间 / 应用中心 /
 * 我的待办 / 训练数据中心)归纳,不是营销虚词,描述的是该功能真实能做什么。
 *
 * paragraphs:占位页顶部流式打字机逐段输出的总览。打字机对**静态文案**做分块
 * 渲染,不调用任何 LLM —— 单机版要求完全离线可用,且文案固定。
 */

import type { DiagramId } from './diagrams';

export interface OnlineFeature {
  /** 路由 key,占位页路由形如 /online/<key> */
  key: string;
  /** 侧边栏 / Tab 标题 */
  title: string;
  /** lucide 图标名(与 deriveIcon 对齐) */
  icon: string;
  /** 一句话定位,显示在占位页标题下方 */
  tagline: string;
  /** 流式输出的功能总览段落(逐段打字机渲染) */
  paragraphs: ReadonlyArray<string>;
  /**
   * 深度介绍内容。5 个在线功能都配 rich,占位页检测到后渲染富版:
   * 顶部仍打字机流式输出 paragraphs,下面分多个板块,每块可带界面示意图 /
   * 流程图 / 拓扑图。
   */
  rich: RichFeature;
}

/** 深度介绍页的一个功能板块。 */
export interface RichSection {
  /** 板块小标题 */
  heading: string;
  /** lucide 图标名 */
  icon: string;
  /** 板块说明文字(1~N 段) */
  body: ReadonlyArray<string>;
  /**
   * 配图 mockup 的 id —— 与 TasklistMockups.tsx 导出的界面示意图组件对应。
   * 仅「我的待办」用到(它有真实界面截图风格的手绘图)。
   */
  mockup?: 'views' | 'conversational-form' | 'flow-handoff';
  /**
   * 配图 diagram 的 id —— 与 online/diagrams/ 注册表对应。
   * 流程图(*-flow)/ 拓扑图(*-topology),figcaption 按种类自动标注。
   */
  diagram?: DiagramId;
  /** 该板块的要点清单(可选,以 • 列表呈现) */
  highlights?: ReadonlyArray<string>;
}

/** 深度介绍内容。 */
export interface RichFeature {
  /** 深度介绍页的功能板块,按顺序渲染 */
  sections: ReadonlyArray<RichSection>;
}

